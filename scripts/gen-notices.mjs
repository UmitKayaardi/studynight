// Generates src/legal/licences.json (shown on the Licences page) and THIRD_PARTY_NOTICES.md from the production
// dependency tree, plus the embedding model, which is downloaded at run time.
import { execSync } from 'node:child_process';
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';

const EXCLUDED_PREFIXES = ['@img/sharp-', 'sharp@', 'onnxruntime-node@', '@napi-rs/canvas'];
const VERIFIED = { duck: 'BSD-2-Clause' };
const root = JSON.parse(readFileSync('package.json', 'utf8')).dependencies;

const data = JSON.parse(
  execSync('npx license-checker-rseidelsohn --production --json --excludePrivatePackages', { encoding: 'utf8', maxBuffer: 64 * 1024 * 1024 }),
);
const packages = Object.entries(data)
  .filter(([pkg]) => !EXCLUDED_PREFIXES.some((p) => pkg.startsWith(p)))
  .map(([pkg, info]) => {
    const name = pkg.slice(0, pkg.lastIndexOf('@'));
    const version = pkg.slice(pkg.lastIndexOf('@') + 1);
    const licence = VERIFIED[name] ?? (Array.isArray(info.licenses) ? info.licenses.join(' AND ') : String(info.licenses));
    return { name, version, licence, url: info.repository ?? '', direct: name in root };
  })
  .sort((a, b) => Number(b.direct) - Number(a.direct) || a.name.localeCompare(b.name));

const model = {
  name: 'intfloat/multilingual-e5-small (ONNX conversion Xenova/multilingual-e5-small)',
  version: 'int8',
  licence: 'MIT',
  url: 'https://huggingface.co/Xenova/multilingual-e5-small',
  direct: true,
};

mkdirSync('src/legal', { recursive: true });
writeFileSync('src/legal/licences.json', JSON.stringify({ model, packages }, null, 1) + '\n');

