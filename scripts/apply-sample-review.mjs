// Applies the hand review of the sample decks to the pristine generated decks and writes the shipped decks.
//   samples/generated/<id>.json  — output of scripts/build-samples.ts (never edited by hand)
//   samples/review.json          — review decisions: { "<id>": [{ "prompt": "...", "remove": true } | { "prompt": "...", "set": {...} }] }
//   src/samples/<id>.json        — shipped decks (generated from the two above; idempotent)
// Usage: node scripts/apply-sample-review.mjs
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';

const ORDER = ['solar-system', 'vaccines', 'machine-learning', 'personal-finance', 'fotosentez', 'ciclo-del-agua'];
const review = existsSync('samples/review.json') ? JSON.parse(readFileSync('samples/review.json', 'utf8')) : {};
const ids = readdirSync('samples/generated')
  .filter((f) => f.endsWith('.json'))
  .map((f) => f.replace(/\.json$/, ''))
  .sort((a, b) => (ORDER.indexOf(a) + 1 || 99) - (ORDER.indexOf(b) + 1 || 99));

const index = [];
for (const id of ids) {
  const deck = JSON.parse(readFileSync(`samples/generated/${id}.json`, 'utf8'));
  const entries = review[id] ?? [];
  let removed = 0;
  let patched = 0;
  for (const e of entries) {
    const i = deck.questions.findIndex((q) => q.content.prompt === e.prompt);
    if (i < 0) {
      console.warn(`${id}: review entry not found: ${e.prompt.slice(0, 60)}`);
      continue;
    }
    if (e.remove) {
      deck.questions.splice(i, 1);
      removed++;
    } else if (e.set) {
      deck.questions[i].content = { ...deck.questions[i].content, ...e.set };
      patched++;
    }
  }
  writeFileSync(`src/samples/${id}.json`, JSON.stringify(deck, null, 1) + '\n');
  index.push({ id, title: deck.title, language: deck.language, description: deck.description, questions: deck.questions.length });
  console.log(`${id}: ${removed} removed, ${patched} corrected, ${deck.questions.length} questions shipped`);
}

writeFileSync(
  'src/samples/index.ts',
  `/** Metadata of the built-in sample decks (generated by scripts/apply-sample-review.mjs). */\nconst samples: Array<{ id: string; title: string; language: string; description: string; questions: number }> = ${JSON.stringify(index, null, 2)};\nexport default samples;\n`,
);
